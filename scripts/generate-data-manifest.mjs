// Generates src/data/bundledData.ts — a static require() manifest for the bundled 5etools
// data, driven by the source→filename maps in each category's index.json.
//
// Metro can only bundle require() calls with static string-literal paths, so we cannot
// require(`./bestiary-${src}.json`) at runtime. This script emits one literal require per
// source (wrapped in a thunk so each file is only pulled/parsed when that source is loaded).
//
// Run after updating the bundled data:  node scripts/generate-data-manifest.mjs
//
// NOTE: this only bundles bestiary + spells (+ the spell-source lookup). It intentionally
// does NOT bundle data/adventure, data/book or data/class (those add ~90MB and aren't used).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DATA_DIR = path.join(ROOT, 'src', 'data', 'data');
const OUT_FILE = path.join(ROOT, 'src', 'data', 'bundledData.ts');

// Bump when the bundled data snapshot is refreshed from 5etools.
const DATA_VERSION = '2.32.0';

/** Read a category index.json ({ SOURCE: filename }) and keep only entries whose file exists. */
function readCategoryIndex(category) {
    const idxPath = path.join(DATA_DIR, category, 'index.json');
    const idx = JSON.parse(fs.readFileSync(idxPath, 'utf8'));
    const entries = [];
    for (const [source, filename] of Object.entries(idx)) {
        const abs = path.join(DATA_DIR, category, filename);
        if (fs.existsSync(abs)) {
            entries.push([source, filename]);
        } else {
            console.warn(`[skip] ${category}: ${source} -> ${filename} (file missing)`);
        }
    }
    // Stable ordering for deterministic output
    entries.sort((a, b) => a[0].localeCompare(b[0]));
    return entries;
}

function emitBundleMap(constName, category, entries) {
    const lines = entries.map(
        ([source, filename]) =>
            `    ${JSON.stringify(source)}: () => require('./data/${category}/${filename}'),`
    );
    return `export const ${constName}: Record<string, () => any> = {\n${lines.join('\n')}\n};\n`;
}

// The class/ folder has no index.json — discover the per-class files directly.
function listClassFiles() {
    return fs.readdirSync(path.join(DATA_DIR, 'class'))
        .filter(f => f.startsWith('class-') && f.endsWith('.json') && !f.startsWith('fluff-'))
        .sort();
}

function emitClassFiles(files) {
    const lines = files.map(f => `    () => require('./data/class/${f}'),`);
    return `export const CLASS_FILES: Array<() => any> = [\n${lines.join('\n')}\n];\n`;
}

const bestiary = readCategoryIndex('bestiary');
const spells = readCategoryIndex('spells');
const classFiles = listClassFiles();

const header = `// AUTO-GENERATED by scripts/generate-data-manifest.mjs — DO NOT EDIT BY HAND.
// Static require() manifest for the offline-bundled 5etools data.
// Regenerate with:  node scripts/generate-data-manifest.mjs

/** Version of the bundled 5etools data snapshot. */
export const DATA_VERSION = ${JSON.stringify(DATA_VERSION)};
`;

const body = [
    header,
    `// ${bestiary.length} bestiary sources`,
    emitBundleMap('BESTIARY_BUNDLE', 'bestiary', bestiary),
    `// ${spells.length} spell sources`,
    emitBundleMap('SPELL_BUNDLE', 'spells', spells),
    `// Spell → class availability lookup (source → spell → class → book → bool)`,
    `export const SPELL_SOURCE_LOOKUP = (): any => require('./data/generated/gendata-spell-source-lookup.json');`,
    ``,
    `// Conditions, diseases & statuses ({ condition: [...], disease: [...], status: [...] })`,
    `export const CONDITIONS_DISEASES = (): any => require('./data/conditionsdiseases.json');`,
    ``,
    `// Single-file reference content ({ action: [...] } / { feat: [...] } / { background: [...] })`,
    `export const ACTIONS = (): any => require('./data/actions.json');`,
    `export const FEATS = (): any => require('./data/feats.json');`,
    `export const BACKGROUNDS = (): any => require('./data/backgrounds.json');`,
    ``,
    `// Items: specific/named items ({ item: [...] }) + base equipment & abbreviation tables`,
    `export const ITEMS = (): any => require('./data/items.json');`,
    `export const ITEMS_BASE = (): any => require('./data/items-base.json');`,
    ``,
    `// Rules glossary ({ variantrule: [...] })`,
    `export const VARIANT_RULES = (): any => require('./data/variantrules.json');`,
    ``,
    `// "World" & extra reference content (single files, entries-based)`,
    `export const DEITIES = (): any => require('./data/deities.json');`,
    `export const CULTS_BOONS = (): any => require('./data/cultsboons.json');`,
    `export const REWARDS = (): any => require('./data/rewards.json');`,
    `export const TRAPS_HAZARDS = (): any => require('./data/trapshazards.json');`,
    `export const BASTIONS = (): any => require('./data/bastions.json');`,
    `export const LANGUAGES = (): any => require('./data/languages.json');`,
    `export const OBJECTS = (): any => require('./data/objects.json');`,
    `export const OPTIONAL_FEATURES = (): any => require('./data/optionalfeatures.json');`,
    `export const CHAR_OPTIONS = (): any => require('./data/charcreationoptions.json');`,
    `export const SENSES = (): any => require('./data/senses.json');`,
    `export const SKILLS = (): any => require('./data/skills.json');`,
    `export const PSIONICS = (): any => require('./data/psionics.json');`,
    `export const VEHICLES = (): any => require('./data/vehicles.json');`,
    ``,
    `// Library INDEXES only (the heavy per-book/adventure content is fetched on demand, not bundled)`,
    `export const BOOKS_INDEX = (): any => require('./data/books.json');`,
    `export const ADVENTURES_INDEX = (): any => require('./data/adventures.json');`,
    ``,
    `// Races & subraces ({ race: [...], subrace: [...] })`,
    `export const RACES = (): any => require('./data/races.json');`,
    ``,
    `// Classes: one file per class ({ class, subclass, classFeature, subclassFeature }).`,
    emitClassFiles(classFiles),
    '',
].join('\n');

fs.writeFileSync(OUT_FILE, body, 'utf8');
console.log(
    `Wrote ${path.relative(ROOT, OUT_FILE)}: ${bestiary.length} bestiary + ${spells.length} spell sources.`
);
